import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { isDeepStrictEqual } from "node:util";
import { loadRegistry } from "shadcn/registry";
import prettier from "prettier";
import { checkGraph } from "./check-registry.mjs";
import { itemMetadata, metadataInputs } from "./registry-metadata.mjs";
const cwd = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const registry = await loadRegistry({ cwd }),
  graph = checkGraph(registry.items),
  inputs = await metadataInputs(cwd);
async function visit(file) {
  const source = JSON.parse(await readFile(file, "utf8"));
  for (const item of source.items) {
    const derived = itemMetadata(graph.byName.get(item.name), graph, inputs);
    if (check) {
      if (
        !isDeepStrictEqual(
          { categories: item.categories, meta: item.meta },
          derived,
        )
      )
        throw Error(`Registry metadata drift: ${item.name}`);
    } else Object.assign(item, derived);
  }
  if (!check)
    await writeFile(
      file,
      await prettier.format(JSON.stringify(source), { parser: "json" }),
    );
  for (const include of source.include ?? [])
    await visit(path.resolve(path.dirname(file), include));
}
await visit(path.join(cwd, "registry.json"));
const versionFile = path.join(
  cwd,
  "registry/shared/hooks/use-finstack/version.ts",
);
const version = `// Generated by scripts/gen-metadata.mjs from the built WASM package.\nexport const wasmVersion = ${JSON.stringify(inputs.wasmVersion)};\n`;
if (check) {
  if ((await readFile(versionFile, "utf8")) !== version)
    throw Error("Compiled WASM version drift");
} else await writeFile(versionFile, version);
console.log(
  `${check ? "Checked" : "Generated"} metadata for ${registry.items.length} registry items.`,
);
