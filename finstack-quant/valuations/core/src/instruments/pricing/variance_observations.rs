//! Shared observation schedule generation for realized-variance instruments.

use finstack_quant_core::dates::{
    adjust, resolve_joint_calendar, BusinessDayConvention, Date, DateExt, HolidayCalendar,
    Schedule, StubKind, Tenor, TenorUnit,
};
use finstack_quant_core::math::stats::RealizedVarMethod;

/// Calendar convention for a realized-variance observation schedule.
pub enum VarianceCalendar<'a> {
    /// One named exchange or fixing-publication calendar.
    Single(&'a str),
    /// Joint base/quote currency calendars for FX observations.
    Joint {
        /// Calendar id of the base currency.
        base: &'a str,
        /// Calendar id of the quote currency.
        quote: &'a str,
    },
}

struct ResolvedVarianceCalendar(&'static dyn HolidayCalendar);

impl ResolvedVarianceCalendar {
    fn resolve(spec: VarianceCalendar<'_>) -> finstack_quant_core::Result<Self> {
        match spec {
            VarianceCalendar::Single(id) => {
                Ok(Self(finstack_quant_core::dates::calendar_by_id_strict(id)?))
            }
            VarianceCalendar::Joint { base, quote } => {
                Ok(Self(resolve_joint_calendar(Some(base), Some(quote))?))
            }
        }
    }
}

/// Generate a strictly validated, calendar-adjusted observation schedule.
///
/// Day tenors advance in business-day steps. Week/month/year tenors are
/// generated by the core
/// [`ScheduleBuilder`](finstack_quant_core::dates::ScheduleBuilder),
/// preserving the original roll anchor and optional end-of-month convention. Every observation is then
/// adjusted using the contract's business-day convention.
pub fn variance_observation_dates(
    start: Date,
    maturity: Date,
    frequency: Tenor,
    business_day_convention: BusinessDayConvention,
    end_of_month: bool,
    calendar: VarianceCalendar<'_>,
) -> finstack_quant_core::Result<Vec<Date>> {
    if frequency.count() == 0 {
        return Err(finstack_quant_core::InputError::InvalidTenor {
            tenor: format!("0{:?}", frequency.unit()),
            reason: "count must be positive".to_string(),
        }
        .into());
    }
    let calendar = ResolvedVarianceCalendar::resolve(calendar)?;

    let mut dates = if frequency.unit() == TenorUnit::Days {
        let mut dates = Vec::new();
        // A day tenor counts at most `MAX_TENOR_DAYS` (73,200), so the cast is exact.
        let step = frequency.count() as i32;
        let mut current = adjust(start, business_day_convention, calendar.0)?;
        let end = adjust(maturity, business_day_convention, calendar.0)?;
        while current <= end {
            dates.push(current);
            current = current.add_business_days(step, calendar.0)?;
        }
        if dates.last() != Some(&end) {
            dates.push(end);
        }
        dates
    } else {
        Schedule::builder(start, maturity)?
            .frequency(frequency)
            .stub_rule(StubKind::ShortBack)
            .end_of_month(end_of_month)
            .build()?
            .dates
            .into_iter()
            .map(|date| adjust(date, business_day_convention, calendar.0))
            .collect::<finstack_quant_core::Result<Vec<_>>>()?
    };

    dates.sort_unstable();
    dates.dedup();
    Ok(dates)
}

/// Contractual annualization for a variance observation tenor.
pub fn annualization_factor(frequency: Tenor, trading_days_per_year: f64) -> f64 {
    if let Some(months) = frequency.months() {
        12.0 / months as f64
    } else if frequency.unit() == TenorUnit::Weeks {
        52.0 / f64::from(frequency.count())
    } else if frequency.unit() == TenorUnit::Days {
        trading_days_per_year / f64::from(frequency.count())
    } else {
        trading_days_per_year
    }
}

/// Fraction of a variance swap's estimator samples observed by `as_of`.
///
/// Close-to-close and Yang-Zhang need the first level as an anchor, so their
/// samples are the return intervals between observations; Parkinson,
/// Garman-Klass and Rogers-Satchell count each observed bar as one sample.
///
/// # Arguments
///
/// * `dates` - Contractual observation dates, sorted ascending (see
///   [`variance_observation_dates`]). Observations on `as_of` count as
///   realized.
/// * `as_of` - Valuation date. An empty schedule returns `0.0`; a date on or
///   after the final observation returns `1.0`.
/// * `method` - Realized-variance estimator that defines a sample.
///
/// # Returns
///
/// Realized samples divided by contractual samples, in `[0, 1]`.
///
/// # Errors
///
/// Returns `Error::Validation` when the schedule has no estimator samples
/// before its final observation (a single close-to-close or Yang-Zhang
/// observation has no return interval).
pub fn realized_sample_fraction(
    dates: &[Date],
    as_of: Date,
    method: RealizedVarMethod,
) -> finstack_quant_core::Result<f64> {
    let Some(&last) = dates.last() else {
        return Ok(0.0);
    };
    if as_of >= last {
        return Ok(1.0);
    }
    let anchor = match method {
        // Yang-Zhang's first close anchors the overnight return of the next
        // bar; it is not itself an estimator sample.
        RealizedVarMethod::CloseToClose | RealizedVarMethod::YangZhang => 1,
        RealizedVarMethod::Parkinson
        | RealizedVarMethod::GarmanKlass
        | RealizedVarMethod::RogersSatchell => 0,
    };
    let total = dates.len().saturating_sub(anchor);
    let realized = dates
        .iter()
        .filter(|&&d| d <= as_of)
        .count()
        .saturating_sub(anchor);
    if total == 0 {
        return Err(finstack_quant_core::Error::Validation(
            "variance swap has no return samples".into(),
        ));
    }
    Ok(realized as f64 / total as f64)
}

#[cfg(test)]
mod tests {
    use super::*;
    use time::macros::date;

    #[test]
    fn day_tenor_uses_holiday_calendar_and_business_endpoints() {
        let dates = variance_observation_dates(
            date!(2025 - 07 - 03),
            date!(2025 - 07 - 08),
            Tenor::daily(),
            BusinessDayConvention::Following,
            false,
            VarianceCalendar::Single("USNY"),
        )
        .expect("schedule");
        assert_eq!(
            dates,
            vec![
                date!(2025 - 07 - 03),
                date!(2025 - 07 - 07),
                date!(2025 - 07 - 08),
            ]
        );

        let weekend_end = variance_observation_dates(
            date!(2025 - 07 - 03),
            date!(2025 - 07 - 06),
            Tenor::daily(),
            BusinessDayConvention::Preceding,
            false,
            VarianceCalendar::Single("USNY"),
        )
        .expect("schedule");
        assert_eq!(weekend_end, vec![date!(2025 - 07 - 03)]);
    }

    #[test]
    fn monthly_schedule_preserves_end_of_month_anchor() {
        let dates = variance_observation_dates(
            date!(2025 - 01 - 31),
            date!(2025 - 05 - 31),
            Tenor::monthly(),
            BusinessDayConvention::Unadjusted,
            true,
            VarianceCalendar::Single("USNY"),
        )
        .expect("schedule");
        assert_eq!(dates[2], date!(2025 - 03 - 31));
    }

    #[test]
    fn zero_frequency_is_rejected_without_iteration() {
        let error = Tenor::new(0, TenorUnit::Days).expect_err("zero tenor");
        assert!(error.to_string().contains("count must be positive"));
    }

    #[test]
    fn unknown_calendar_is_rejected() {
        let error = variance_observation_dates(
            date!(2025 - 01 - 01),
            date!(2025 - 02 - 01),
            Tenor::daily(),
            BusinessDayConvention::Following,
            false,
            VarianceCalendar::Single("NOT-A-CALENDAR"),
        )
        .expect_err("unknown calendar");
        assert!(error.to_string().contains("NOT-A-CALENDAR"));
    }
}
