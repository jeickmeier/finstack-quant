//! Basis swap implementation for multi-curve calibration.
//!
//! A basis swap exchanges two floating rate payments with different tenors,
//! capturing the basis spread between them (e.g., 3M vs 6M).
//!
//! # Sign Convention
//!
//! NPV is computed from the perspective of **receiving the primary leg** (with spread)
//! and **paying the reference leg**:
//!
//! - **Positive NPV**: Primary leg receiver is in-the-money
//! - **Negative NPV**: Primary leg receiver is out-of-the-money
//!
//! This convention aligns with ISDA standards where the spread-receiving party
//! is considered "long" the basis swap.
//!
//! # Shared Infrastructure
//!
//! This module uses canonical cashflow periods, shared fixing/projection
//! helpers, and relative discount factors. Coupon PV retains the exact adjusted
//! payment date generated by the contractual schedule.

use finstack_quant_core::dates::{BusinessDayConvention, DayCount, Tenor};
use finstack_quant_core::market_data::traits::Discounting;
use finstack_quant_core::{
    Result, dates::Date, market_data::context::MarketContext, money::Money, types::InstrumentId,
};

use finstack_quant_cashflows::builder::{
    CashFlowSchedule, FloatingRateFallback, Notional, PrincipalExchange, merge_cashflow_schedules,
};
use finstack_quant_core::validation;
use finstack_quant_valuations_core::impl_instrument_base;
use rust_decimal::Decimal;

use crate::FloatLegSpec;
use crate::irs::cashflow::float_leg_coupon_spec;

/// Basis swap instrument that exchanges two floating rate payments with different tenors.
///
/// A basis swap allows parties to exchange floating rate payments based on different
/// reference rates (e.g., 3M SOFR vs 6M SOFR) plus an optional spread on one leg.
/// The primary leg typically receives the spread, while the reference leg pays flat.
///
/// Each leg owns its own dates, discount curve, calendar, and stub conventions,
/// following the IRS leg-centric pattern.
///
/// # Cross-Currency (XCCY) Basis Swaps
///
/// **Important**: This implementation supports **single-currency** basis swaps only.
/// For cross-currency basis swaps, use `XccySwap` instead.
///
/// # Examples
/// ```rust
/// use finstack_quant_core::{dates::*, money::Money, currency::Currency, types::CurveId};
/// use finstack_quant_valuations_rates::basis_swap::BasisSwap;
/// use finstack_quant_valuations_rates::FloatLegSpec;
/// use time::Month;
///
/// let start = Date::from_calendar_date(2024, Month::January, 3).expect("valid date");
/// let end = Date::from_calendar_date(2025, Month::January, 3).expect("valid date");
///
/// let primary_leg = FloatLegSpec {
///     index_id: "3M-SOFR".into(),
///     forward_curve_id: CurveId::new("3M-SOFR"),
///     discount_curve_id: CurveId::new("OIS"),
///     start,
///     end,
///     frequency: Tenor::quarterly(),
///     day_count: DayCount::Act360,
///     business_day_convention: BusinessDayConvention::ModifiedFollowing,
///     calendar_id: None,
///     fixing_calendar_id: None,
///     end_of_month: false,
///     stub: StubKind::ShortFront,
///     spread_bp: rust_decimal::Decimal::from(5),
///     payment_lag_days: 0,
///     reset_lag_days: 0,
///     compounding: Default::default(),
/// };
///
/// let reference_leg = FloatLegSpec {
///     index_id: "6M-SOFR".into(),
///     forward_curve_id: CurveId::new("6M-SOFR"),
///     discount_curve_id: CurveId::new("OIS"),
///     start,
///     end,
///     frequency: Tenor::semi_annual(),
///     day_count: DayCount::Act360,
///     business_day_convention: BusinessDayConvention::ModifiedFollowing,
///     calendar_id: None,
///     fixing_calendar_id: None,
///     end_of_month: false,
///     stub: StubKind::ShortFront,
///     spread_bp: rust_decimal::Decimal::ZERO,
///     payment_lag_days: 0,
///     reset_lag_days: 0,
///     compounding: Default::default(),
/// };
///
/// let swap = BasisSwap::builder()
///     .id("BASIS_SWAP_001".into())
///     .notional(Money::from((1_000_000_i64, Currency::USD)))
///     .primary_leg(primary_leg)
///     .reference_leg(reference_leg)
///     .allow_calendar_fallback(true)
///     .attributes(Default::default())
///     .build().expect("valid basis swap");
/// ```
#[derive(
    Clone,
    Debug,
    finstack_quant_valuations_macros::FinancialBuilder,
    serde::Serialize,
    serde::Deserialize,
)]
#[cfg_attr(feature = "json-schema", derive(schemars::JsonSchema))]
#[serde(deny_unknown_fields)]
pub struct BasisSwap {
    /// Unique identifier for this instrument.
    pub id: InstrumentId,
    /// Notional amount for both legs.
    pub notional: Money,
    /// Primary leg that typically receives the spread.
    pub primary_leg: FloatLegSpec,
    /// Reference leg that typically pays flat.
    pub reference_leg: FloatLegSpec,
    /// Allow calendar-day fallback when the calendar cannot be resolved.
    ///
    /// When `false` (default), missing calendars are treated as an input error to
    /// avoid silently misaligning schedule and payment-lag conventions.
    #[builder(default)]
    #[serde(default)]
    pub allow_calendar_fallback: bool,
    /// Allow both legs to reference the same forward curve.
    ///
    /// When `false` (default), having identical forward curves on both legs produces
    /// a validation error, as this is almost always a configuration mistake (NPV would
    /// equal spread × annuity by construction). Set to `true` only for testing or
    /// deliberate same-index spread trades.
    #[builder(default)]
    #[serde(default)]
    pub allow_same_curve: bool,
    /// Instrument-owned pricing inputs.
    #[builder(default)]
    #[serde(
        default,
        skip_serializing_if = "finstack_quant_valuations_core::instruments::pricing_overrides::InstrumentPricingOverrides::is_empty"
    )]
    pub instrument_pricing_overrides:
        finstack_quant_valuations_core::instruments::pricing_overrides::InstrumentPricingOverrides,
    /// Metric-time pricing configuration.
    #[builder(default)]
    #[serde(
        default,
        skip_serializing_if = "finstack_quant_valuations_core::instruments::pricing_overrides::MetricPricingOverrides::is_empty"
    )]
    pub metric_pricing_overrides:
        finstack_quant_valuations_core::instruments::pricing_overrides::MetricPricingOverrides,
    /// Scenario-only pricing adjustments.
    #[builder(default)]
    #[serde(
        default,
        skip_serializing_if = "finstack_quant_valuations_core::instruments::pricing_overrides::ScenarioPricingOverrides::is_empty"
    )]
    pub scenario_pricing_overrides:
        finstack_quant_valuations_core::instruments::pricing_overrides::ScenarioPricingOverrides,
    /// Attributes for instrument selection and tagging.
    pub attributes: finstack_quant_core::types::Attributes,
}

impl BasisSwap {
    /// Creates a new basis swap with the specified parameters.
    ///
    /// Dates, discount curves, calendars, and stub conventions are on each leg.
    ///
    /// # Errors
    /// Returns an error if:
    /// - Either leg has `start >= end` (invalid swap tenor)
    /// - Both legs reference the same forward curve (build with
    ///   `BasisSwap::builder().allow_same_curve(true)` or set the JSON field `allow_same_curve`
    ///   for an intentional same-index spread trade)
    /// - Any lag is negative
    /// - A leg calendar is absent or unknown; explicit fallback must be set on
    ///   `BasisSwap::builder()` before construction
    /// - A simple-compounded leg references an overnight index
    ///
    /// # Arguments
    ///
    /// * `id` - Trade identifier stored on the instrument and used in results and serialization.
    /// * `notional` - Swap notional in the shared leg currency; must be finite and strictly positive.
    /// * `primary_leg` - Spread-receiving floating leg (dates, index, discount curve, and spread).
    /// * `reference_leg` - Flat floating leg paid against the primary. Must use a different
    ///   forward curve; same-curve trades are built with `BasisSwap::builder()` and
    ///   `allow_same_curve(true)`.
    pub fn new(
        id: impl Into<InstrumentId>,
        notional: Money,
        primary_leg: FloatLegSpec,
        reference_leg: FloatLegSpec,
    ) -> Result<Self> {
        let id: InstrumentId = id.into();
        let swap = Self {
            id,
            notional,
            primary_leg,
            reference_leg,
            allow_calendar_fallback: false,
            allow_same_curve: false,
            instrument_pricing_overrides: Default::default(),
            metric_pricing_overrides: Default::default(),
            scenario_pricing_overrides: Default::default(),
            attributes: finstack_quant_core::types::Attributes::default(),
        };
        swap.validate()?;
        Ok(swap)
    }

    /// Validate structural invariants independently of the constructor.
    ///
    /// This is required for Serde-backed Rust/Python/WASM construction, which
    /// does not pass through [`BasisSwap::new`].
    pub fn validate(&self) -> Result<()> {
        validation::validate_money_gt(self.notional, 0.0, "BasisSwap notional")?;
        if self.primary_leg.start >= self.primary_leg.end {
            return Err(finstack_quant_core::Error::Validation(format!(
                "BasisSwap '{}' primary leg has start ({}) >= end ({}); leg must have positive tenor",
                self.id, self.primary_leg.start, self.primary_leg.end
            )));
        }
        if self.reference_leg.start >= self.reference_leg.end {
            return Err(finstack_quant_core::Error::Validation(format!(
                "BasisSwap '{}' reference leg has start ({}) >= end ({}); leg must have positive tenor",
                self.id, self.reference_leg.start, self.reference_leg.end
            )));
        }
        if !self.allow_same_curve
            && self.primary_leg.forward_curve_id == self.reference_leg.forward_curve_id
        {
            return Err(finstack_quant_core::Error::Validation(format!(
                "BasisSwap '{}' has identical forward curves on both legs ({}); set allow_same_curve=true only for an intentional same-index spread trade",
                self.id,
                self.primary_leg.forward_curve_id.as_str()
            )));
        }
        Self::validate_leg_lags(self.id.as_str(), "primary", &self.primary_leg)?;
        Self::validate_leg_lags(self.id.as_str(), "reference", &self.reference_leg)?;
        self.resolve_leg_calendar("primary", &self.primary_leg)?;
        self.resolve_leg_calendar("reference", &self.reference_leg)?;
        finstack_quant_valuations_core::instruments::pricing::overnight_conventions::reject_simple_overnight(
            self.primary_leg.index_id.as_str(),
            &self.primary_leg.compounding,
        )?;
        finstack_quant_valuations_core::instruments::pricing::overnight_conventions::reject_simple_overnight(
            self.reference_leg.index_id.as_str(),
            &self.reference_leg.compounding,
        )?;
        Ok(())
    }

    /// Create a canonical example USD 3M SOFR vs 1M SOFR basis swap (5Y, $10M notional).
    ///
    /// Returns a 5-year basis swap with the primary leg on 3M SOFR (receiving 5bp spread)
    /// and the reference leg on 1M SOFR (flat).
    pub fn example() -> Result<Self> {
        use finstack_quant_core::currency::Currency;
        use finstack_quant_core::dates::StubKind;
        use finstack_quant_core::types::CurveId;
        use time::Month;

        let start = Date::from_calendar_date(2024, Month::January, 3).map_err(|e| {
            finstack_quant_core::Error::Validation(format!("Invalid example start date: {}", e))
        })?;
        let end = Date::from_calendar_date(2029, Month::January, 3).map_err(|e| {
            finstack_quant_core::Error::Validation(format!("Invalid example end date: {}", e))
        })?;

        let primary_leg = FloatLegSpec {
            end_of_month: false,
            fixing_calendar_id: None,
            index_id: "USD-SOFR-3M".into(),
            forward_curve_id: CurveId::new("USD-SOFR-3M"),
            discount_curve_id: CurveId::new("USD-OIS"),
            start,
            end,
            frequency: Tenor::quarterly(),
            day_count: DayCount::Act360,
            business_day_convention: BusinessDayConvention::ModifiedFollowing,
            calendar_id: Some("weekends_only".into()),
            stub: StubKind::ShortFront,
            spread_bp: Decimal::from(5),
            payment_lag_days: 0,
            reset_lag_days: 0,
            compounding: Default::default(),
        };

        let reference_leg = FloatLegSpec {
            end_of_month: false,
            fixing_calendar_id: None,
            index_id: "USD-SOFR-1M".into(),
            forward_curve_id: CurveId::new("USD-SOFR-1M"),
            discount_curve_id: CurveId::new("USD-OIS"),
            start,
            end,
            frequency: Tenor::monthly(),
            day_count: DayCount::Act360,
            business_day_convention: BusinessDayConvention::ModifiedFollowing,
            calendar_id: Some("weekends_only".into()),
            stub: StubKind::ShortFront,
            spread_bp: Decimal::ZERO,
            payment_lag_days: 0,
            reset_lag_days: 0,
            compounding: Default::default(),
        };

        Self::new(
            "BASIS-SWAP-USD-3M1M-5Y",
            Money::from((10_000_000_i64, Currency::USD)),
            primary_leg,
            reference_leg,
        )
    }

    fn validate_leg_lags(id: &str, leg_name: &str, leg: &FloatLegSpec) -> Result<()> {
        if leg.compounding
            == finstack_quant_cashflows::builder::FloatingLegCompounding::SimpleAverage
        {
            return Err(finstack_quant_core::Error::Validation(format!(
                "BasisSwap '{id}' {leg_name}_leg.compounding = simple_average is not supported; \
                 use simple or a compounded_* variant"
            )));
        }
        if leg.payment_lag_days < 0 {
            return Err(finstack_quant_core::Error::Validation(format!(
                "BasisSwap '{}' {} leg has negative payment_lag_days ({}); \
                 payment lag must be non-negative",
                id, leg_name, leg.payment_lag_days
            )));
        }
        if leg.reset_lag_days < 0 {
            return Err(finstack_quant_core::Error::Validation(format!(
                "BasisSwap '{}' {} leg has negative reset_lag_days ({}); \
                 reset lag must be non-negative",
                id, leg_name, leg.reset_lag_days
            )));
        }
        Ok(())
    }

    fn resolve_leg_calendar<'a>(&self, leg_name: &str, leg: &'a FloatLegSpec) -> Result<&'a str> {
        if let Some(id) = leg.calendar_id.as_deref()
            && finstack_quant_core::dates::calendar_by_id_strict(id).is_ok()
        {
            return Ok(id);
        }
        if self.allow_calendar_fallback {
            return Ok(finstack_quant_core::dates::WEEKENDS_ONLY_ID);
        }
        Err(finstack_quant_core::Error::Validation(format!(
            "BasisSwap '{}' {} leg requires a resolvable calendar_id; set allow_calendar_fallback=true to opt into weekends_only",
            self.id, leg_name
        )))
    }

    /// Calculates the present value of a floating rate leg.
    ///
    /// Uses canonical adjusted payment dates for both the cashflow cutoff and
    /// discounting, and compensated summation for numerical stability.
    ///
    /// # Arguments
    ///
    /// * `leg` - Contractual leg conventions, including spread in basis points,
    ///   the payment calendar, and the optional separate fixing calendar.
    /// * `market` - Discount/projection curves and realized index fixings keyed
    ///   by the leg's curve identifiers.
    /// * `as_of` - Valuation date; payments on or before it are settled, and
    ///   earlier reset dates require exact historical fixings.
    pub fn pv_float_leg(
        &self,
        leg: &FloatLegSpec,
        market: &MarketContext,
        as_of: Date,
    ) -> Result<Money> {
        if leg.payment_lag_days < 0 || leg.reset_lag_days < 0 {
            return Err(finstack_quant_core::Error::Validation(
                "BasisSwap leg lags must be non-negative".to_string(),
            ));
        }

        let spread_bp = leg.spread_bp.as_f64();
        crate::rate_validation::validate_rate_magnitude(
            spread_bp,
            5000.0,
            "BasisSwap leg spread",
            1.0,
            "bp",
            "Spread is in basis points (e.g., Decimal::from(5) for 5bp). \
             If this is intentional for stress testing, consider using a dedicated stress API.",
        )?;

        let typical_spread_bp = 500.0;
        if spread_bp.abs() > typical_spread_bp {
            tracing::warn!(
                instrument_id = %self.id.as_str(),
                spread_bp,
                "BasisSwap leg spread {}bp is outside typical market range (±500bp). \
                 Verify this is intentional and not a unit conversion error.",
                leg.spread_bp
            );
        }

        let disc = market.get_discount(&leg.discount_curve_id)?;
        let currency = self.notional.currency();
        if leg.compounding != finstack_quant_cashflows::builder::FloatingLegCompounding::Simple {
            let schedule = self.floating_leg_schedule(leg, market, as_of)?;
            let mut acc = finstack_quant_core::math::summation::NeumaierAccumulator::new();
            for flow in schedule.get_flows() {
                if flow.get_date() <= as_of {
                    continue;
                }
                let df = disc.as_ref().df_between_dates(as_of, flow.get_date())?;
                acc.add(flow.get_amount().amount() * df)?;
            }
            return Money::from_model_value(acc.get_total()?, currency);
        }
        let fwd = market.get_forward(&leg.forward_curve_id)?;

        let calendar_id = self.resolve_leg_calendar("priced", leg)?;
        let fixing_calendar = finstack_quant_core::dates::calendar_by_id_strict(
            leg.fixing_calendar_id.as_deref().unwrap_or(calendar_id),
        )?;
        // The fixing calendar can differ from the payment calendar. Compute
        // resets below without altering the canonical payments.
        let periods = finstack_quant_cashflows::builder::build_periods(leg.schedule_params(
            calendar_id,
            None,
            false,
        ))?;

        let fixings = finstack_quant_core::market_data::fixings::get_fixing_series(
            market,
            leg.index_id.as_str(),
        )
        .ok();

        let mut acc = finstack_quant_core::math::summation::NeumaierAccumulator::new();
        for period in periods {
            if period.payment_date <= as_of {
                continue;
            }
            let reset_date = finstack_quant_cashflows::builder::compute_reset_date(
                period.accrual_start,
                leg.reset_lag_days,
                leg.business_day_convention,
                fixing_calendar,
            )?;
            let index_rate = if let Some(fixing) =
                finstack_quant_cashflows::builder::observed_index_fixing(
                    reset_date,
                    fixings,
                    leg.index_id.as_str(),
                    as_of,
                )? {
                fixing
            } else {
                finstack_quant_cashflows::builder::project_index_rate(
                    reset_date,
                    &fwd,
                    period.accrual_start,
                    period.accrual_end,
                    period.accrual_year_fraction,
                )?
            };
            let coupon = self.notional.amount()
                * (index_rate + spread_bp * finstack_quant_core::math::units::ONE_BASIS_POINT)
                * period.accrual_year_fraction;
            let df = disc.as_ref().df_between_dates(as_of, period.payment_date)?;
            acc.add(coupon * df)?;
        }

        Money::from_model_value(acc.get_total()?, currency)
    }

    /// Calculates the discounted accrual sum (annuity) for a leg.
    pub fn annuity_for_leg(
        &self,
        leg: &FloatLegSpec,
        market: &MarketContext,
        as_of: Date,
    ) -> Result<f64> {
        if leg.payment_lag_days < 0 {
            return Err(finstack_quant_core::Error::Validation(
                "BasisSwap payment lag must be non-negative".to_string(),
            ));
        }

        let disc = market.get_discount(&leg.discount_curve_id)?;

        let periods = finstack_quant_cashflows::builder::build_periods(leg.schedule_params(
            self.resolve_leg_calendar("cashflow", leg)?,
            Some(leg.reset_lag_days),
            false,
        ))?;

        if periods.is_empty() {
            return Err(finstack_quant_core::Error::Validation(
                "BasisSwap leg schedule must contain at least 2 dates".to_string(),
            ));
        }

        let overnight =
            leg.compounding != finstack_quant_cashflows::builder::FloatingLegCompounding::Simple;
        let overnight_calendar = if overnight {
            Some(
                finstack_quant_valuations_core::instruments::pricing::overnight::resolve_overnight_fixing_calendar(
                    Some(leg.fixing_calendar_id.as_deref().unwrap_or(self.resolve_leg_calendar("cashflow", leg)?)),
                    self.notional.currency(),
                    "BasisSwap",
                )?,
            )
        } else {
            None
        };
        let overnight_fwd = if overnight {
            Some(market.get_forward(&leg.forward_curve_id)?)
        } else {
            None
        };
        let overnight_fixings = if overnight {
            finstack_quant_core::market_data::fixings::get_fixing_series(
                market,
                leg.index_id.as_str(),
            )
            .ok()
        } else {
            None
        };

        let mut annuity = 0.0;
        for period in periods {
            if period.payment_date <= as_of {
                continue;
            }
            let df = disc.as_ref().df_between_dates(as_of, period.payment_date)?;
            let year_fraction =
                if let (Some(calendar), Some(fwd)) = (overnight_calendar, overnight_fwd.as_ref()) {
                    match project_overnight_period(
                        leg,
                        &period,
                        fwd.as_ref(),
                        overnight_fixings,
                        calendar,
                        as_of,
                        false,
                    )? {
                        Some(projection) => projection.accrual_year_fraction,
                        None => continue,
                    }
                } else {
                    period.accrual_year_fraction
                };
            annuity += year_fraction * df;
        }

        use finstack_quant_valuations_core::constants::ANNUITY_EPSILON;
        if annuity < ANNUITY_EPSILON {
            return Err(finstack_quant_core::Error::Validation(format!(
                "BasisSwap annuity ({:.2e}) is below minimum threshold ({:.2e}). \
                 This may indicate all periods have expired or extreme discounting scenarios.",
                annuity, ANNUITY_EPSILON
            )));
        }

        Ok(annuity)
    }

    pub(super) fn floating_leg_schedule(
        &self,
        leg: &FloatLegSpec,
        market: &MarketContext,
        as_of: Date,
    ) -> Result<CashFlowSchedule> {
        if leg.compounding != finstack_quant_cashflows::builder::FloatingLegCompounding::Simple {
            return self.overnight_leg_schedule(leg, market, as_of);
        }
        let calendar_id = self.resolve_leg_calendar("cashflow", leg)?;
        let mut builder = CashFlowSchedule::builder();
        let _ = builder
            .principal(self.notional, leg.start, leg.end)
            .principal_exchange(PrincipalExchange::None)
            .floating_cf(float_leg_coupon_spec(
                leg,
                calendar_id,
                false,
                FloatingRateFallback::Error,
            ));
        builder.build_as_of(market, as_of)
    }

    fn overnight_leg_schedule(
        &self,
        leg: &FloatLegSpec,
        market: &MarketContext,
        as_of: Date,
    ) -> Result<CashFlowSchedule> {
        use finstack_quant_core::cashflow::{CFKind, CashFlowParams};

        let calendar_id = self.resolve_leg_calendar("cashflow", leg)?;
        let calendar =
            finstack_quant_valuations_core::instruments::pricing::overnight::resolve_overnight_fixing_calendar(
                Some(leg.fixing_calendar_id.as_deref().unwrap_or(calendar_id)),
                self.notional.currency(),
                "BasisSwap",
            )?;
        let periods = finstack_quant_cashflows::builder::build_periods(leg.schedule_params(
            calendar_id,
            Some(leg.reset_lag_days),
            false,
        ))?;
        let fwd = market.get_forward(&leg.forward_curve_id)?;
        let fixings = finstack_quant_core::market_data::fixings::get_fixing_series(
            market,
            leg.index_id.as_str(),
        )
        .ok();
        let spread_bp = leg.spread_bp.as_f64();
        let mut flows = Vec::with_capacity(periods.len());
        let mut projected_fixings = Vec::new();
        for period in periods {
            if period.payment_date <= as_of {
                continue;
            }
            let Some(projection) = project_overnight_period(
                leg,
                &period,
                fwd.as_ref(),
                fixings,
                calendar,
                as_of,
                true,
            )?
            else {
                continue;
            };
            projected_fixings.extend(projection.projected_fixings(leg.index_id.as_str()));
            let coupon_amount = projection.coupon_amount(
                self.notional.amount(),
                spread_bp * finstack_quant_core::math::units::ONE_BASIS_POINT,
            );
            let all_in_rate = if projection.accrual_year_fraction.abs() > f64::EPSILON {
                (projection.compound_factor - 1.0) / projection.accrual_year_fraction
                    + spread_bp * finstack_quant_core::math::units::ONE_BASIS_POINT
            } else {
                spread_bp * finstack_quant_core::math::units::ONE_BASIS_POINT
            };
            flows.push(
                CashFlowParams::new(
                    period.payment_date,
                    period.reset_date,
                    Money::from_model_value(coupon_amount, self.notional.currency())?,
                    CFKind::Floating,
                    projection.accrual_year_fraction,
                    Some(all_in_rate),
                )
                .build()?,
            );
        }
        Ok(finstack_quant_cashflows::schedule_from_classified_flows(
            flows,
            leg.day_count,
            finstack_quant_cashflows::ScheduleBuildOpts {
                notional_hint: Some(self.notional),
                meta: finstack_quant_cashflows::builder::CashFlowMeta {
                    projected_fixings,
                    ..Default::default()
                },
            },
        ))
    }
}

/// Projects one compounded overnight period of `leg` on its fixing calendar.
///
/// Adjusts the accrual window to business days (RFR compounding steps only
/// over business days) and compounds the overnight forwards, reading
/// historical fixings for observations before `as_of`. Returns `None` when
/// the adjusted window is empty.
pub(super) fn project_overnight_period(
    leg: &FloatLegSpec,
    period: &finstack_quant_cashflows::builder::SchedulePeriod,
    fwd: &finstack_quant_core::market_data::term_structures::ForwardCurve,
    fixings: Option<&finstack_quant_core::market_data::scalars::ScalarTimeSeries>,
    calendar: &dyn finstack_quant_core::dates::HolidayCalendar,
    as_of: Date,
    need_observation_exposures: bool,
) -> Result<
    Option<
        finstack_quant_valuations_core::instruments::pricing::overnight::OvernightCouponProjection,
    >,
> {
    use finstack_quant_valuations_core::instruments::pricing::overnight::{
        OvernightCouponProjectionInput, OvernightProjectionCurve,
        adjust_overnight_accrual_boundaries, project_overnight_coupon,
    };
    let (accrual_start, accrual_end) = adjust_overnight_accrual_boundaries(
        period.accrual_start,
        period.accrual_end,
        leg.business_day_convention,
        calendar,
    )?;
    if accrual_end <= accrual_start {
        return Ok(None);
    }
    project_overnight_coupon(OvernightCouponProjectionInput {
        curve: OvernightProjectionCurve::Forward(fwd),
        fixings,
        fixing_id: leg.index_id.as_str(),
        as_of,
        accrual_start,
        accrual_end,
        end_is_termination_date: None,
        day_count: leg.day_count,
        coupon_frequency: Some(leg.frequency),
        coupon_period: (accrual_start, accrual_end),
        compounding: &leg.compounding,
        fixing_calendar: calendar,
        compounded_spread: 0.0,
        need_observation_exposures,
    })
    .map(Some)
}

// Attributable implementation is provided by the impl_instrument! macro

// Use the macro to implement Instrument with pricing
impl finstack_quant_valuations_core::instruments::Instrument for BasisSwap {
    fn includes_valuation_date_cashflows(&self) -> bool {
        false
    }
    impl_instrument_base!(
        finstack_quant_valuations_core::pricer::InstrumentType::BasisSwap,
        crate::RATES
    );

    fn validate_invariants(&self) -> finstack_quant_core::Result<()> {
        BasisSwap::validate(self)
    }

    fn market_dependencies(
        &self,
    ) -> finstack_quant_core::Result<finstack_quant_valuations_core::instruments::MarketDependencies>
    {
        let mut deps = finstack_quant_valuations_core::instruments::MarketDependencies::new();
        deps.add_discount_curve(self.primary_leg.discount_curve_id.clone());
        deps.add_discount_curve(self.reference_leg.discount_curve_id.clone());
        deps.add_forward_curve(self.primary_leg.forward_curve_id.clone());
        deps.add_forward_curve(self.reference_leg.forward_curve_id.clone());
        deps.add_series_id(finstack_quant_core::market_data::fixings::fixing_series_id(
            self.primary_leg.index_id.as_str(),
        ));
        deps.add_series_id(finstack_quant_core::market_data::fixings::fixing_series_id(
            self.reference_leg.index_id.as_str(),
        ));
        Ok(deps)
    }

    fn base_value(
        &self,
        curves: &finstack_quant_core::market_data::context::MarketContext,
        as_of: finstack_quant_core::dates::Date,
    ) -> finstack_quant_core::Result<finstack_quant_core::money::Money> {
        // pv_float_leg builds its own period schedule internally; computing leg_schedule
        // here would be redundant work on the calibration hot path.
        let primary_pv = self.pv_float_leg(&self.primary_leg, curves, as_of)?;
        let reference_pv = self.pv_float_leg(&self.reference_leg, curves, as_of)?;

        // NPV from perspective of receiving primary leg (with spread), paying reference leg
        primary_pv.checked_sub(reference_pv)
    }

    fn expiry(&self) -> Option<finstack_quant_core::dates::Date> {
        Some(self.primary_leg.end)
    }

    finstack_quant_valuations_core::impl_focused_pricing_overrides!();
}

impl finstack_quant_cashflows::CashflowScheduleSource for BasisSwap {
    fn notional(&self) -> finstack_quant_core::Result<Option<Money>> {
        Ok(Some(self.notional))
    }

    fn raw_cashflow_schedule(
        &self,
        market: &MarketContext,
        _as_of: Date,
    ) -> finstack_quant_core::Result<CashFlowSchedule> {
        let primary = self.floating_leg_schedule(&self.primary_leg, market, _as_of)?;
        let reference = self
            .floating_leg_schedule(&self.reference_leg, market, _as_of)?
            .scale_amounts(-1.0)?;
        Ok(merge_cashflow_schedules(
            [primary, reference],
            Notional::par(self.notional.amount(), self.notional.currency())?,
            self.primary_leg.day_count,
        )
        .with_representation(finstack_quant_cashflows::builder::CashflowRepresentation::Projected))
    }
}
