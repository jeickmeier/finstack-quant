//! Yield-to-N-years calculators for term loans.
//!
//! Computes IRR to fixed horizons (2y, 3y, 4y) using kind-aware cashflow
//! filtering and outstanding principal at the horizon date for redemption.

use crate::term_loan::TermLoan;
use finstack_quant_core::dates::DateExt;
use finstack_quant_valuations_core::metrics::{MetricCalculator, MetricContext};

use super::irr_helpers::{
    cached_full_schedule, solve_irr_to_date, target_price_from_quote_or_model,
};

macro_rules! define_ytn {
    ($name:ident, $years:expr) => {
        /// Yield-to-N-year calculator for callable term loans (generated by macro)
        pub(crate) struct $name;

        impl MetricCalculator for $name {
            fn calculate(&self, context: &mut MetricContext) -> finstack_quant_core::Result<f64> {
                let as_of = context.as_of;
                let schedule = cached_full_schedule(context)?;
                // Horizon yields use the same settlement price as YTM/YTC/YTW.
                let (maturity, target_price) = {
                    let loan: &TermLoan = context.instrument_as()?;
                    let target_price = target_price_from_quote_or_model(
                        loan,
                        &schedule,
                        &context.curves,
                        as_of,
                        context.base_value,
                    )?;
                    (loan.maturity, target_price)
                };

                // Feb 29 clamps to Feb 28 in a non-leap target year.
                let target = as_of.add_months(12 * $years)?;
                let exercise_date = if target < maturity { target } else { maturity };
                if exercise_date <= as_of {
                    return Err(finstack_quant_core::InputError::InvalidDateRange.into());
                }

                solve_irr_to_date(context, target_price, exercise_date)
            }
        }
    };
}

define_ytn!(Yt2yCalculator, 2);
define_ytn!(Yt3yCalculator, 3);
define_ytn!(Yt4yCalculator, 4);
