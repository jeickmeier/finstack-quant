def currency_rows(path: Path) -> list[tuple[str, int, int, str]]:
    """Load unique ISO codes, numeric identifiers, and decimal scales."""
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != ["code", "numeric", "minor_units", "name"]:
            raise ValueError(f"{path}: invalid currency CSV header")
        rows = [(r["code"], int(r["numeric"]), int(r["minor_units"]), r["name"]) for r in reader]
    if not rows or len({r[0] for r in rows}) != len(rows) or len({r[1] for r in rows}) != len(rows):
        raise ValueError(f"{path}: empty table or duplicate currency identifier")
    for code, numeric, decimals, name in rows:
        if not (
            len(code) == 3
            and code.isascii()
            and code.isalpha()
            and code.isupper()
            and 0 <= numeric <= 999
            and 0 <= decimals <= 4
            and name
            and "\n" not in name
        ):
            raise ValueError(f"{path}: invalid currency row {code}")
    return sorted(rows)


def render_currency(rows: list[tuple[str, int, int, str]]) -> str:
    """Generate the enum, minor-unit lookup, and numeric-code conversion."""
    lines = [
        "// Generated by build/generate_reference_data.py from data/iso_4217.csv - DO NOT EDIT",
        "",
        "#[derive(Debug, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, serde::Serialize, serde::Deserialize)]",
        '#[cfg_attr(feature = "json-schema", derive(schemars::JsonSchema))]',
        "/// ISO 4217 currency enumeration",
        "#[repr(u16)]",
        "pub enum Currency {",
    ]
    for code, numeric, _, name in rows:
        lines += [f"    /// {name} ({numeric})", f"    {code} = {numeric},"]
    lines += [
        "}",
        "",
        "/// Every ISO 4217 currency, in code order (the enum declaration order).",
        f"pub(crate) static ALL_CURRENCIES: [Currency; {len(rows)}] = [",
    ]
    lines += [f"    Currency::{code}," for code, _, _, _ in rows]
    lines += [
        "];",
        "",
        "impl Currency {",
        '    /// ISO 4217 alphabetic code, such as `"USD"`.',
        "    #[inline]",
        "    pub const fn code(self) -> &'static str {",
        "        match self {",
    ]
    lines += [f'            Currency::{code} => "{code}",' for code, _, _, _ in rows]
    lines += [
        "        }",
        "    }",
        "",
        "    /// ISO-4217 decimal precision (minor units) for this currency (e.g. USD → 2).",
        "    #[inline]",
        "    pub const fn decimals(self) -> u8 {",
        "        match self {",
    ]
    for scale in sorted({decimals for _, _, decimals, _ in rows}):
        codes = [code for code, _, decimals, _ in rows if decimals == scale]
        lines += [f"            {'| ' if i else ''}Currency::{code}" for i, code in enumerate(codes)]
        lines[-1] += f" => {scale},"
    lines += [
        "        }",
        "    }",
        "}",
        "",
        "impl TryFrom<u16> for Currency {",
        "    type Error = crate::Error;",
        "",
        "    fn try_from(code: u16) -> Result<Self, Self::Error> {",
        "        match code {",
    ]
    lines += [f"            {numeric} => Ok(Currency::{code})," for code, numeric, _, _ in rows]
    lines += [
        '            _ => Err(crate::Error::Validation(format!("invalid ISO 4217 currency code: {code}"))),',
        "        }",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


SIFMA_HEADER = "year,month,class_a,class_b,class_c,class_d"

SifmaRow = tuple[int, int, tuple[int | None, ...]]


def parse_sifma_day(value: str, path: Path, line_number: int) -> int | None:
    """Parse one class settlement day; an empty field means the class is unpublished."""
    if value == "":
        return None
    try:
        day = int(value)
    except ValueError as error:
        raise ValueError(f"{path}:{line_number}: invalid settlement day {value!r}") from error
    if not 1 <= day <= 31:
        raise ValueError(f"{path}:{line_number}: settlement day must be 1-31, got {day}")
    return day


def sifma_rows(path: Path) -> list[SifmaRow]:
    """Load SIFMA settlement days per (year, month), sorted and checked for real dates."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != SIFMA_HEADER:
        raise ValueError(f"{path}: expected header '{SIFMA_HEADER}'")
    rows: list[SifmaRow] = []
    for line_number, line in enumerate(lines[1:], start=2):
        fields = line.split(",")
        if len(fields) != 6:
            raise ValueError(f"{path}:{line_number}: expected six comma-separated fields")
        try:
            year, month = int(fields[0]), int(fields[1])
        except ValueError as error:
            raise ValueError(f"{path}:{line_number}: invalid year or month {fields[:2]!r}") from error
        if not 1 <= month <= 12:
            raise ValueError(f"{path}:{line_number}: month must be 1-12, got {month}")
        days = tuple(parse_sifma_day(value, path, line_number) for value in fields[2:])
        if all(day is None for day in days):
            raise ValueError(f"{path}:{line_number}: row must publish at least one class")
        last_day = calendar.monthrange(year, month)[1]
        if any(day is not None and day > last_day for day in days):
            raise ValueError(f"{path}:{line_number}: {year}-{month:02d} has only {last_day} days")
        rows.append((year, month, days))
    rows.sort(key=lambda row: (row[0], row[1]))
    if len({(year, month) for year, month, _ in rows}) != len(rows):
        raise ValueError(f"{path}: duplicate year/month row")
    return rows


def render_sifma(rows: list[SifmaRow]) -> str:
    """Render the SIFMA settlement lookup as a checked-in Rust static."""

    def render_day(day: int | None) -> str:
        return "None" if day is None else f"Some({day})"

    lines = [
        "// Auto-generated from data/sifma_settlements.csv by build/generate_reference_data.py - DO NOT EDIT",
        "// Each row: (year, month, [class A, class B, class C, class D] days).",
        "pub(crate) static SIFMA_SETTLEMENTS: &[(i32, u8, [Option<u8>; 4])] = &[",
    ]
    for year, month, days in rows:
        lines.append(f"    ({year}, {month}, [{', '.join(render_day(day) for day in days)}]),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def cache_year_range() -> tuple[int, int]:
    """Read `BASE_YEAR`/`END_YEAR` from the calendar algorithms module."""
    source = ALGO_SOURCE.read_text(encoding="utf-8")
    years = {
        name: int(re.search(rf"pub\(crate\) const {name}: i32 = (\d+);", source).group(1))
        for name in ("BASE_YEAR", "END_YEAR")
    }
    return years["BASE_YEAR"], years["END_YEAR"]


def date_rows(path: Path) -> list[tuple[int, int, int]]:
    """Validate one Gregorian festival date for every supported calendar year."""
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != ["year", "month", "day"]:
            raise ValueError(f"{path}: invalid date CSV header")
        rows = sorted((int(r["year"]), int(r["month"]), int(r["day"])) for r in reader)
    base_year, end_year = cache_year_range()
    if [r[0] for r in rows] != list(range(base_year, end_year + 1)):
        raise ValueError(f"{path}: expected one date per year from {base_year} through {end_year}")
    for row in rows:
        dt.date(*row)
    return rows


RUST_KEYWORDS = {"as", "do", "fn", "if", "in", "mod", "pub", "ref", "try", "use"}

