def render_wasm_currency_factories(rows: list[tuple[str, int, int, str]]) -> str:
    """Generate the WASM `Currency` static factories, one per ISO code."""
    lines = []
    for code, numeric, _, name in rows:
        lower = code.lower()
        ident = f"r#{lower}" if lower in RUST_KEYWORDS else lower
        lines += [
            f"    /// {name} (`{code}`, ISO-4217 numeric {numeric}).",
            "    ///",
            f"    /// @returns The `{code}` currency.",
            f'    {ident} as "{lower}" => {code},',
        ]
    return WASM_CURRENCY_PREFIX + "\n".join(lines) + "\n" + WASM_CURRENCY_SUFFIX


def render_cny(rows: list[tuple[int, int, int]]) -> str:
    """Generate the Chinese New Year table used by the calendar algorithms."""
    lo, hi = cache_year_range()
    lines = [
        "// Generated by build/generate_reference_data.py from data/chinese_new_year.csv - DO NOT EDIT",
        "",
        "/// Chinese New Year dates as (month, day), indexed by Gregorian year.",
        "static CNY_DATES_MAP: phf::Map<i32, (u8, u8)> = phf::phf_map! {",
    ]
    lines += [f"    {year}i32 => ({month}, {day})," for year, month, day in rows]
    lines += [
        "};",
        "",
        "/// Gregorian date of the `(month, day)` tabulated for `year` in `table`.",
        "fn tabulated_date(year: i32, table: &phf::Map<i32, (u8, u8)>) -> Option<Date> {",
        "    let &(month, day) = table.get(&year)?;",
        "    Date::from_calendar_date(year, Month::try_from(month).ok()?, day).ok()",
        "}",
        "",
        f"/// Chinese New Year (Spring Festival) date in `year`, or `None` outside {lo}-{hi}.",
        "#[inline]",
        "pub(crate) fn cny_date(year: i32) -> Option<Date> {",
        "    tabulated_date(year, &CNY_DATES_MAP)",
        "}",
    ]
    return "\n".join(lines) + "\n"


def render_festivals(tables: dict[str, list[tuple[int, int, int]]]) -> str:
    """Render the shared lunar/solar festival and local equinox lookup helpers."""
    lo, hi = cache_year_range()
    lines = [
        "// Generated by build/generate_reference_data.py from data/* festival/equinox CSVs - DO NOT EDIT",
        f"// Coverage: {lo}-{hi} (matches the validated holiday calendar range).",
    ]
    for name, description in FESTIVAL_TABLES.items():
        table_name = f"{name.upper()}_DATES_MAP"
        lines += [
            "",
            f"/// {description} dates as (month, day), indexed by Gregorian year.",
            f"static {table_name}: phf::Map<i32, (u8, u8)> = phf::phf_map! {{",
        ]
        lines += [f"    {year}i32 => ({month}, {day})," for year, month, day in tables[name]]
        lines += [
            "};",
            "",
            f"/// {description} date in `year`, or `None` outside {lo}-{hi}.",
            "#[inline]",
            f"pub(crate) fn {name}_date(year: i32) -> Option<Date> {{",
            f"    tabulated_date(year, &{table_name})",
            "}",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write tables, or fail without mutation when --check detects drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--crate-root", type=Path, default=CRATE_ROOT)
    parser.add_argument("--wasm-root", type=Path)
    args = parser.parse_args()
    crate_root = args.crate_root.resolve()
    wasm_root = (args.wasm_root or crate_root.parent.parent / "finstack-quant-wasm").resolve()
    generated = crate_root / "src/generated"
    currencies = currency_rows(crate_root / "data/iso_4217.csv")
    outputs = {
        generated / "currency_generated.rs": render_currency(currencies),
        generated / "cny_generated.rs": render_cny(date_rows(crate_root / "data/chinese_new_year.csv")),
        generated / "festivals_generated.rs": render_festivals({
            name: date_rows(crate_root / "data" / f"{name}.csv") for name in FESTIVAL_TABLES
        }),
        generated / "sifma_settlements_generated.rs": render_sifma(
            sifma_rows(crate_root / "data/sifma_settlements.csv")
        ),
    }
    # Core can be generated without a sibling WASM checkout.
    wasm_directory = wasm_root / "src/api/core"
    if wasm_directory.is_dir():
        outputs[wasm_directory / "currency_statics.rs"] = render_wasm_currency_factories(currencies)
    stale = []
    for path, expected in outputs.items():
        actual = path.read_text(encoding="utf-8") if path.exists() else None
        if actual == expected:
            continue
        if args.check:
            stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    if stale:
        paths = ", ".join(str(path) for path in stale)
        raise SystemExit(f"Stale generated reference data: {paths}; run mise run gen-write")


if __name__ == "__main__":
    main()
