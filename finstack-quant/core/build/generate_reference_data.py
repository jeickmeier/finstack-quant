"""Render currency and Chinese New Year Rust tables from maintained CSV inputs.

Run through ``mise run core-gen-data`` or ``mise run core-check-data``. The CSVs
are authoritative; this tool never fetches or changes their financial data.
"""

from __future__ import annotations

import argparse
import csv
import datetime as dt
from pathlib import Path

CRATE_ROOT = Path(__file__).resolve().parents[1]


def currency_rows(path: Path) -> list[tuple[str, int, int, str]]:
    """Load unique ISO codes, numeric identifiers, and decimal scales."""
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != ["code", "numeric", "minor_units", "name"]:
            raise ValueError(f"{path}: invalid currency CSV header")
        rows = [(r["code"], int(r["numeric"]), int(r["minor_units"]), r["name"]) for r in reader]
    if not rows or len({r[0] for r in rows}) != len(rows) or len({r[1] for r in rows}) != len(rows):
        raise ValueError(f"{path}: empty table or duplicate currency identifier")
    for code, numeric, decimals, name in rows:
        if not (
            len(code) == 3
            and code.isascii()
            and code.isalpha()
            and code.isupper()
            and 0 <= numeric <= 999
            and 0 <= decimals <= 4
            and name
            and "\n" not in name
        ):
            raise ValueError(f"{path}: invalid currency row {code}")
    return sorted(rows)


def render_currency(rows: list[tuple[str, int, int, str]]) -> str:
    """Generate the enum, minor-unit table, and numeric-code conversion."""
    lines = [
        "// Generated by build/generate_reference_data.py from data/iso_4217.csv - DO NOT EDIT",
        "use strum_macros::{AsRefStr, EnumIter, EnumString, Display};",
        "",
        "#[derive(Debug, Copy, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, AsRefStr, EnumString, EnumIter, Display, serde::Serialize, serde::Deserialize)]",
        '#[cfg_attr(feature = "json-schema", derive(schemars::JsonSchema))]',
        "/// ISO 4217 currency enumeration",
        "#[strum(ascii_case_insensitive)]",
        "#[repr(u16)]",
        "pub enum Currency {",
    ]
    for code, numeric, _, name in rows:
        lines += [f"    /// {name} ({numeric})", f"    {code} = {numeric},"]
    lines += [
        "}",
        "",
        "/// Number of decimal places (minor units) for each ISO 4217 currency, keyed by numeric code.",
        "pub static MINOR_UNITS: phf::Map<u16, u8> = phf::phf_map! {",
    ]
    lines += [f"    {numeric}u16 => {decimals}," for _, numeric, decimals, _ in rows]
    lines += [
        "};",
        "",
        "impl TryFrom<u16> for Currency {",
        "    type Error = TryFromCurrencyError;",
        "",
        "    fn try_from(code: u16) -> Result<Self, Self::Error> {",
        "        match code {",
    ]
    lines += [f"            {numeric} => Ok(Currency::{code})," for code, numeric, _, _ in rows]
    lines += ["            _ => Err(TryFromCurrencyError(code)),", "        }", "    }", "}"]
    return "\n".join(lines) + "\n"


def cny_rows(path: Path) -> list[tuple[int, int, int]]:
    """Validate one Gregorian festival date for every supported calendar year."""
    with path.open(encoding="utf-8", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != ["year", "month", "day"]:
            raise ValueError(f"{path}: invalid date CSV header")
        rows = sorted((int(r["year"]), int(r["month"]), int(r["day"])) for r in reader)
    if [r[0] for r in rows] != list(range(1970, 2151)):
        raise ValueError(f"{path}: expected one date per year from 1970 through 2150")
    for row in rows:
        dt.date(*row)
    return rows


def render_cny(rows: list[tuple[int, int, int]]) -> str:
    """Generate the Chinese New Year table used by the calendar algorithms."""
    lines = [
        "// Generated by build/generate_reference_data.py from data/chinese_new_year.csv - DO NOT EDIT",
        "",
        "/// Chinese New Year dates as (month, day), indexed by Gregorian year.",
        "static CNY_DATES_MAP: phf::Map<i32, (u8, u8)> = phf::phf_map! {",
    ]
    lines += [f"    {year}i32 => ({month}, {day})," for year, month, day in rows]
    lines += [
        "};",
        "",
        "/// Get Chinese New Year date for a supported year.",
        "#[inline]",
        "pub(crate) fn cny_date_for_year(year: i32) -> Option<(u8, u8)> {",
        "    CNY_DATES_MAP.get(&year).copied()",
        "}",
        "",
        "/// Check if a date is Chinese New Year.",
        "#[inline]",
        "pub(crate) fn is_cny_date(year: i32, month: u8, day: u8) -> bool {",
        "    CNY_DATES_MAP.get(&year).is_some_and(|&(m, d)| m == month && d == day)",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write tables, or fail without mutation when --check detects drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {
        "currency_generated.rs": render_currency(currency_rows(CRATE_ROOT / "data/iso_4217.csv")),
        "cny_generated.rs": render_cny(cny_rows(CRATE_ROOT / "data/chinese_new_year.csv")),
    }
    stale = []
    for name, expected in outputs.items():
        path = CRATE_ROOT / "src/generated" / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                stale.append(name)
        else:
            path.write_text(expected, encoding="utf-8")
    if stale:
        raise SystemExit(f"Stale generated reference data: {', '.join(stale)}; run mise run core-gen-data")


if __name__ == "__main__":
    main()
